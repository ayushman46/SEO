/**
 * geo.ai-crawler-probe (T016 C, ADR-017): pure evaluation of the live crawler probe done in
 * net/probe.ts. We request the same URLs with a labelled simulated User-Agent per AI bot and
 * compare against what our own crawler (seenhqbot) got. When a bot is refused although
 * robots.txt allows it, we name the layer that refused it from response headers / block page.
 */
import type { Severity } from "../../types";
import { plural, unavailable, type BotProbe, type CheckOutcome, type CrawlerProbe, type IssueSeed, type ProbeResponse, type ProbeTarget } from "../../context";
import type { IssueKey } from "../../issues";

const def = { id: "geo.ai-crawler-probe", category: "geo", label: "AI crawler access (simulated test)" } as const;

export const PROBE_HONESTY =
  "Simulated from our servers, so a site that verifies crawler IP addresses may treat the real bot differently.";

export const PROBE_BOTS = [
  { name: "GPTBot", token: "GPTBot/1.3", product: "OpenAI training", kind: "training" },
  { name: "OAI-SearchBot", token: "OAI-SearchBot/1.3", product: "ChatGPT search", kind: "search" },
  { name: "ChatGPT-User", token: "ChatGPT-User/1.0", product: "ChatGPT (live browsing)", kind: "search" },
  { name: "ClaudeBot", token: "ClaudeBot/1.0", product: "Anthropic training", kind: "training" },
  { name: "PerplexityBot", token: "PerplexityBot/1.0", product: "Perplexity", kind: "search" },
  { name: "bingbot", token: "bingbot/2.0", product: "Bing search and Copilot", kind: "search" },
] as const;
const WEIGHT = { search: 3, training: 1 } as const;

/* ── Response verdicts ── */

export type Verdict = "ok" | "refused" | "challenged" | "differs" | "rate_limited" | "untested";

export const CHALLENGE_BODY =
  /challenge-platform|cf-chl|_cf_chl_opt|<title>\s{0,20}(just a moment|attention required|access denied|security check)|captcha-delivery|g-recaptcha|h-captcha|verify you are human|are you a robot/i;
const REFUSED_STATUSES = new Set([401, 403, 406, 451, 503]);

/**
 * Bots whose operators publish crawler IP ranges, so sites may verify them by IP and refuse a
 * request that only carries the name (R3 M3). ClaudeBot is not listed: Anthropic doesn't
 * publish its crawler IP ranges.
 */
export const IP_VERIFIED_BOTS = new Set(["bingbot", "GPTBot", "OAI-SearchBot", "ChatGPT-User", "PerplexityBot"]);
/** Size below which a 200 counts as "different content" vs the crawler's copy. */
const DIFFERS_RATIO = 0.3;
const MIN_BASELINE_FOR_SIZE = 2_000;

export function isChallenge(r: ProbeResponse): boolean {
  const h = r.headers;
  if ((h["cf-mitigated"] ?? "").toLowerCase().includes("challenge")) return true;
  if ((h["x-vercel-mitigated"] ?? "").toLowerCase() === "challenge") return true;
  return r.method === "GET" && CHALLENGE_BODY.test(r.body.slice(0, 20_000));
}

export function verdict(t: ProbeTarget, r: ProbeResponse | null, bodyCap: number): Verdict {
  if (!r) return "untested";
  const base = t.baselineStatus;
  // Our own burst may trigger rate limiting: never count a 429 as a block (R3 M4).
  if (r.status === 429 && base !== 429) return "rate_limited";
  const baseOk = base !== null && base < 400;
  if (isChallenge(r) && baseOk) return "challenged";
  if (
    r.method === "GET" &&
    t.kind === "page" &&
    r.status >= 200 &&
    r.status < 300 &&
    t.baselineSize !== null &&
    t.baselineSize >= MIN_BASELINE_FOR_SIZE &&
    r.size < DIFFERS_RATIO * Math.min(t.baselineSize, bodyCap)
  ) {
    return "differs";
  }
  if (r.status === base) return "ok";
  if (r.status >= 400 && (baseOk || REFUSED_STATUSES.has(r.status))) return base === r.status ? "ok" : "refused";
  return "ok";
}

/* ── Which layer refused it ── */

export type Layer = "cloudflare" | "vercel" | "akamai" | "sucuri" | "wordfence" | "imperva" | "aws" | "fastly" | "netlify" | "datadome" | "host";

export const LAYER_NAME: Record<Layer, string> = {
  cloudflare: "Cloudflare",
  vercel: "Vercel Firewall",
  akamai: "Akamai",
  sucuri: "Sucuri Website Firewall",
  wordfence: "Wordfence (WordPress plugin)",
  imperva: "Imperva",
  aws: "AWS (CloudFront / AWS WAF)",
  fastly: "Fastly",
  netlify: "Netlify",
  datadome: "DataDome",
  host: "your host or firewall",
};

/** Name the refusing layer from headers and the block page. Body markers win over CDN headers. */
export function classifyLayer(r: ProbeResponse): { layer: Layer; evidence: string } {
  const h = r.headers;
  const server = (h.server ?? "").toLowerCase();
  const body = r.body.slice(0, 20_000);
  if (/generated by wordfence|wordfence|access to this site has been limited by the site owner/i.test(body)) {
    return { layer: "wordfence", evidence: "Wordfence block page" };
  }
  if (h["x-sucuri-id"] || h["x-sucuri-block"] || server.includes("sucuri") || /sucuri website firewall/i.test(body)) {
    return { layer: "sucuri", evidence: h["x-sucuri-block"] ? "x-sucuri-block header" : "Sucuri headers" };
  }
  if (h["cf-mitigated"] || h["cf-ray"] || server === "cloudflare" || /challenge-platform|cf-chl|cloudflare ray id/i.test(body)) {
    return { layer: "cloudflare", evidence: h["cf-mitigated"] ? `cf-mitigated: ${h["cf-mitigated"]}` : "server: cloudflare / cf-ray" };
  }
  if (h["x-vercel-mitigated"] || h["x-vercel-id"] || server === "vercel") {
    return { layer: "vercel", evidence: h["x-vercel-mitigated"] ? `x-vercel-mitigated: ${h["x-vercel-mitigated"]}` : "Vercel headers" };
  }
  if (h["akamai-grn"] || server.includes("akamaighost") || /errors\.edgesuite\.net|reference&#32;&#35;|reference #\d/i.test(body)) {
    return { layer: "akamai", evidence: h["akamai-grn"] ? "akamai-grn header" : "Akamai block page" };
  }
  if (h["x-iinfo"] || /imperva/i.test(h["x-cdn"] ?? "") || /incapsula incident/i.test(body)) {
    return { layer: "imperva", evidence: "Imperva headers" };
  }
  if (h["x-datadome"] || server.includes("datadome") || /captcha-delivery\.com/i.test(body)) {
    return { layer: "datadome", evidence: "DataDome headers" };
  }
  if (h["x-amz-cf-id"] || /cloudfront/i.test(h.via ?? "") || server.includes("awselb") || /request blocked[\s\S]{0,3000}cloudfront/i.test(body)) {
    return { layer: "aws", evidence: "CloudFront / AWS headers" };
  }
  if (h["x-nf-request-id"] || server.includes("netlify")) return { layer: "netlify", evidence: "Netlify headers" };
  if (h["x-fastly-request-id"] || /\bcache-[a-z]{3}/i.test(h["x-served-by"] ?? "")) return { layer: "fastly", evidence: "Fastly headers" };
  return { layer: "host", evidence: server ? `server: ${server.slice(0, 40)}` : "no identifying headers" };
}

const LAYER_ISSUE: Record<Layer, IssueKey> = {
  cloudflare: "geo.ai-crawler-probe:blocked-cloudflare",
  vercel: "geo.ai-crawler-probe:blocked-vercel",
  akamai: "geo.ai-crawler-probe:blocked-akamai",
  sucuri: "geo.ai-crawler-probe:blocked-sucuri",
  wordfence: "geo.ai-crawler-probe:blocked-wordfence",
  imperva: "geo.ai-crawler-probe:blocked-imperva",
  aws: "geo.ai-crawler-probe:blocked-aws",
  fastly: "geo.ai-crawler-probe:blocked-host",
  netlify: "geo.ai-crawler-probe:blocked-host",
  datadome: "geo.ai-crawler-probe:blocked-host",
  host: "geo.ai-crawler-probe:blocked-host",
};

function pathOf(u: string): string {
  try {
    const x = new URL(u);
    return `${x.pathname}${x.search}`;
  } catch {
    return u;
  }
}

const SKIP_SUMMARY: Record<Extract<CrawlerProbe, { status: "skipped" }>["reason"], string> = {
  not_run: "The simulated AI-crawler test wasn't run for this audit.",
  no_time: "There wasn't enough time left for the simulated AI-crawler test, so it was skipped.",
  aborted: "The simulated AI-crawler test was cancelled.",
  error: "The simulated AI-crawler test couldn't be completed.",
};

export function crawlerProbeOutcome(probe: CrawlerProbe, bodyCap = 64 * 1024): CheckOutcome {
  if (probe.status === "skipped") return unavailable(def, `${SKIP_SUMMARY[probe.reason]} ${PROBE_HONESTY}`);
  if (probe.status === "inconclusive") {
    return unavailable(
      def,
      `Our own crawler (seenhqbot) was refused by your site (status ${probe.baselineStatus}), so the simulated AI-crawler test is inconclusive. ${PROBE_HONESTY}`,
    );
  }

  const targetOf = new Map(probe.targets.map((t) => [t.url, t]));
  const byBot = new Map<string, { tested: number; refused: { p: BotProbe; v: Verdict }[]; differs: BotProbe[]; homeRefused: boolean }>();
  const rateLimited = new Set<string>();
  for (const p of probe.probes) {
    const t = targetOf.get(p.url);
    if (!t) continue;
    const v = verdict(t, p.response, bodyCap);
    if (v === "rate_limited") rateLimited.add(p.bot);
    if (v === "untested" || v === "rate_limited") continue;
    const e = byBot.get(p.bot) ?? { tested: 0, refused: [], differs: [], homeRefused: false };
    e.tested++;
    if (v === "refused" || v === "challenged") {
      e.refused.push({ p, v });
      if (t.kind === "page" && t === probe.targets[0]) e.homeRefused = true;
    } else if (v === "differs") e.differs.push(p);
    byBot.set(p.bot, e);
  }
  const untestedByRate = [...rateLimited].filter((b) => !byBot.has(b));
  const rateNote =
    (rateLimited.size ? ` Not tested (rate limited): ${untestedByRate.length ? untestedByRate.join(", ") : "some requests"}.` : "") +
    (probe.cached ? " (Result reused from a test of this site in the last 15 minutes.)" : "");
  if (byBot.size === 0) {
    return unavailable(def, `The simulated AI-crawler test got no usable responses in time.${rateNote} ${PROBE_HONESTY}`);
  }

  // Classify every refusal once.
  const refusals = new Map<string, { p: BotProbe; v: Verdict; layer: Layer; evidence: string }[]>();
  for (const [bot, e] of byBot) {
    refusals.set(
      bot,
      e.refused.map(({ p, v }) => ({ p, v, ...classifyLayer(p.response!) })),
    );
  }
  const refusingBots = [...refusals.entries()].filter(([, r]) => r.length > 0).map(([b]) => b);
  // R3 M3: only IP-verifiable bots refused, no named WAF, and other bots got through, so the
  // site may simply verify crawler IPs. Low severity, careful wording, small score effect.
  const ipVerificationLikely =
    refusingBots.length > 0 &&
    refusingBots.length < byBot.size &&
    refusingBots.every((b) => IP_VERIFIED_BOTS.has(b) && refusals.get(b)!.every((r) => r.layer === "host"));

  let total = 0;
  let lost = 0;
  const layerHits = new Map<
    Layer,
    { bots: Set<string>; urls: Set<string>; paths: Set<string>; statuses: Set<string>; evidence: Set<string>; search: boolean; full: boolean }
  >();
  const differsBots = new Set<string>();
  const differsUrls = new Set<string>();
  const blockedNames: string[] = [];
  for (const b of PROBE_BOTS) {
    const e = byBot.get(b.name);
    if (!e) continue;
    total += WEIGHT[b.kind];
    const full = e.homeRefused || e.refused.length * 2 >= e.tested;
    if (e.refused.length) {
      lost += WEIGHT[b.kind] * (full ? 1 : e.refused.length / e.tested) * (ipVerificationLikely ? 0.25 : 1);
      blockedNames.push(b.name);
      for (const { p, v, layer, evidence } of refusals.get(b.name)!) {
        const hit = layerHits.get(layer) ?? {
          bots: new Set(),
          urls: new Set(),
          paths: new Set(),
          statuses: new Set(),
          evidence: new Set(),
          search: false,
          full: false,
        };
        hit.bots.add(b.name);
        hit.paths.add(pathOf(p.url));
        hit.urls.add(p.url);
        hit.statuses.add(v === "challenged" ? `challenge page (${p.response!.status})` : String(p.response!.status));
        hit.evidence.add(evidence);
        hit.search ||= b.kind === "search";
        hit.full ||= full;
        layerHits.set(layer, hit);
      }
    }
    if (e.differs.length) {
      differsBots.add(b.name);
      for (const p of e.differs) differsUrls.add(p.url);
      lost += WEIGHT[b.kind] * 0.25 * (e.differs.length / e.tested);
    }
  }

  const issues: IssueSeed[] = [];
  for (const [layer, hit] of layerHits) {
    if (ipVerificationLikely && layer === "host") {
      issues.push({
        key: "geo.ai-crawler-probe:ip-verification-likely",
        severity: "low",
        share: 1,
        affectedUrls: [...hit.urls],
        detail: `${[...hit.bots].join(", ")} got ${[...hit.statuses].join(", ")} on ${[...hit.paths].slice(0, 5).join(", ")}, while other simulated crawlers got through.`,
      });
      continue;
    }
    const severity: Severity = hit.search ? (hit.full ? "high" : "medium") : "medium";
    issues.push({
      key: LAYER_ISSUE[layer],
      severity,
      share: hit.search ? 3 : 1,
      affectedUrls: [...hit.urls],
      detail:
        `Refused by ${LAYER_NAME[layer]} (${[...hit.evidence].join(", ")}): ${[...hit.bots].join(", ")} got ${[...hit.statuses].join(", ")} on ${[...hit.paths].slice(0, 5).join(", ")}, ` +
        `while robots.txt allows them and our own crawler got a normal response.`,
    });
  }
  if (differsBots.size) {
    issues.push({
      key: "geo.ai-crawler-probe:different-content",
      share: 1,
      affectedUrls: [...differsUrls],
      detail: `Much smaller pages were returned to: ${[...differsBots].join(", ")}.`,
    });
  }

  const tested = byBot.size;
  const score = total > 0 ? Math.max(0, 1 - lost / total) : 1;
  const layers = [...layerHits.keys()].map((l) => LAYER_NAME[l]);
  if (issues.length === 0) {
    return {
      ...def,
      status: "pass",
      score: 1,
      summary: `All ${plural(tested, "simulated AI crawler")} tested got the same response as our own crawler.${rateNote} ${PROBE_HONESTY}`,
      issues: [],
    };
  }
  const summary = ipVerificationLikely
    ? `${blockedNames.join(", ")} ${blockedNames.length === 1 ? "was" : "were"} refused while other crawlers got through: your site may be verifying crawler IP addresses; we cannot tell from outside.${rateNote} ${PROBE_HONESTY}`
    : blockedNames.length
      ? `${blockedNames.join(", ")} ${blockedNames.length === 1 ? "was" : "were"} refused (${layers.join(", ")}) although robots.txt allows ${blockedNames.length === 1 ? "it" : "them"}.${rateNote} ${PROBE_HONESTY}`
      : `${[...differsBots].join(", ")} got much smaller pages than our own crawler.${rateNote} ${PROBE_HONESTY}`;
  const s = Math.min(score, 0.99);
  return { ...def, status: s < 0.5 ? "fail" : "warn", score: s, summary, issues };
}
